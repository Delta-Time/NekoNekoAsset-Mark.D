// Regenerates app/src/bindings, the TypeScript declarations of what the UI sends to and
// reads from Rust. ts-rs writes them while `cargo test` runs; this copies them there, adds
// an index and formats them with Biome. Run `pnpm --dir app bindings`.
import { execFileSync } from 'node:child_process';
import { cpSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..', 'app');
const native = join(app, 'src-tauri');
const generated = join(native, 'bindings');
const bindings = join(app, 'src', 'bindings');

rmSync(generated, { recursive: true, force: true });
// IPC JSON carries 64-bit integers as numbers, not bigint.
execFileSync('cargo', ['test', '--lib', '--locked', '--quiet', 'export_bindings'], {
  cwd: native,
  stdio: 'inherit',
  env: { ...process.env, TS_RS_LARGE_INT: 'number' },
});
rmSync(bindings, { recursive: true, force: true });
cpSync(generated, bindings, { recursive: true });
const names = readdirSync(bindings)
  .filter((file) => file.endsWith('.ts'))
  .map((file) => file.slice(0, -3))
  .sort();
writeFileSync(
  join(bindings, 'index.ts'),
  `// Generated by scripts/bindings.mjs from the Rust types. Do not edit this file manually.\n${names
    .map((name) => `export type { ${name} } from './${name}';\n`)
    .join('')}`,
);
execFileSync(
  process.execPath,
  [join(app, 'node_modules/@biomejs/biome/bin/biome'), 'format', '--write', 'src/bindings'],
  { cwd: app, stdio: 'inherit' },
);
